-- Manual class additions and section transfers. Existing tables are unchanged.
CREATE TABLE IF NOT EXISTS tbl_student_class_roster_audit (
    audit_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    operation_key CHAR(64) CHARACTER SET ascii NOT NULL,
    student_id INT UNSIGNED NOT NULL,
    student_number VARCHAR(32) CHARACTER SET ascii NOT NULL,
    student_enrollment_id INT UNSIGNED NOT NULL,
    campus_id INT UNSIGNED NOT NULL,
    college_id INT UNSIGNED NOT NULL,
    ay_id INT UNSIGNED NOT NULL,
    semester TINYINT UNSIGNED NOT NULL,
    program_id INT UNSIGNED NOT NULL,
    section_id INT UNSIGNED NOT NULL,
    offering_id INT UNSIGNED NOT NULL,
    subject_id INT UNSIGNED NOT NULL,
    faculty_id INT UNSIGNED NOT NULL,
    action ENUM('add','transfer') NOT NULL,
    reason_code VARCHAR(32) NOT NULL,
    reason_note VARCHAR(500) NOT NULL DEFAULT '',
    previous_memberships LONGTEXT NOT NULL,
    actor_user_id INT UNSIGNED NOT NULL,
    actor_name VARCHAR(255) NOT NULL,
    recorded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (audit_id),
    UNIQUE KEY uk_roster_audit_operation (operation_key),
    UNIQUE KEY uk_roster_audit_membership (student_enrollment_id),
    KEY idx_roster_audit_scope (college_id,ay_id,semester,subject_id,action),
    KEY idx_roster_audit_student (student_id,recorded_at,audit_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
